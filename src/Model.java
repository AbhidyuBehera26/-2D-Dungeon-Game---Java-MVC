public class Model {
	
	 private GameObject Player;
	 private GameObject Player2;
	 private Controller controller = Controller.getInstance();
	 private CopyOnWriteArrayList<GameObject> EnemiesList  = new CopyOnWriteArrayList<GameObject>();
	 private CopyOnWriteArrayList<GameObject> BulletList  = new CopyOnWriteArrayList<GameObject>();
	 private int Score = 0; 
	 private int Lives = 3;
	 private int Level = 1;
	 private boolean isGameOver = false;
	 private CopyOnWriteArrayList<GameObject> PotionsList  = new CopyOnWriteArrayList<GameObject>();
	 private float difficultySpeedMult = 1.0f;
	 private float difficultySpawnMult = 1.0f;
	 private java.util.HashMap<GameObject, Vector3f> bulletVelocities = new java.util.HashMap<>();
	 private java.util.HashMap<GameObject, Integer> bulletPierces = new java.util.HashMap<>();
	 
	 private util.Vector3f p1Facing = new util.Vector3f(0, 1, 0);
	 private Vector3f p2Facing = new Vector3f(0, 1, 0);
	 
	 private int enemiesToSpawn = 10;
	 private GameObject nextLevelHole = null;

	public Model() {
		// Player 1
		Player = new GameObject("res/red_knight.png", 100, 100, new Point3f(400, 500, 0));
		// Player 2
		Player2 = new GameObject("res/blue_knight.png", 100, 100, new Point3f(600, 500, 0));
		
		// Initial Enemies
		for (int i = 0; i < 5; i++) {
			spawnEnemy();
			enemiesToSpawn--;
		}
	}
	
	private void spawnEnemy() {
		String type = (Math.random() > 0.5) ? "res/goblin.png" : "res/skeleton.png";
		float x, y;
		if (Math.random() > 0.5) {
			x = (Math.random() > 0.5) ? -100 : 1100; // spawn beyond left or right edge
			y = (float)Math.random() * 1000;
		} else {
			x = (float)Math.random() * 1000;
			y = (Math.random() > 0.5) ? -100 : 1100; // spawn beyond top or bottom edge
		}
		EnemiesList.add(new GameObject(type, 100, 100, new Point3f(x, y, 0)));
	}
	
	public void gamelogic() {
		if (isGameOver) return;
		
		if (controller.isKeyF5Pressed()) { saveGame(); controller.setKeyF5Pressed(false); }
		if (controller.isKeyF9Pressed()) { loadGame(); controller.setKeyF9Pressed(false); }

		playerLogic(); 
		enemyLogic();
		bulletLogic();
		collisionLogic();
		
		if (EnemiesList.isEmpty() && enemiesToSpawn <= 0) {
			if (nextLevelHole == null) {
				nextLevelHole = new GameObject("res/blankSprite.png", 200, 100, new Point3f(500, 50, 0));
				BulletList.clear(); // Clear all bullet clutter
			}
		}
	}

	private void collisionLogic() { 
		// Transition check
		if (nextLevelHole != null) {
			if (checkCollision(Player, nextLevelHole) || checkCollision(Player2, nextLevelHole)) {
				Level++;
				enemiesToSpawn = 10 + (Level * 5); // Increase enemies per level
				
				// Set player positions a short distance away from hole safely
				Player.getCentre().setX(500); Player.getCentre().setY(700);
				Player2.getCentre().setX(400); Player2.getCentre().setY(700);
				
				// Spawn first initial chunk
				int initialSpawn = Math.min(5 + Level, enemiesToSpawn);
				for (int i=0; i < initialSpawn; i++) {
					spawnEnemy();
					enemiesToSpawn--;
				}
				nextLevelHole = null; // Remove hole
			}
		}
		
		// Potion Logic
		for (GameObject potion : PotionsList) {
			if (checkCollision(potion, Player) || checkCollision(potion, Player2)) {
				Lives++;
				PotionsList.remove(potion);
			}
		}

		for (GameObject enemy : EnemiesList) {
			for (GameObject bullet : BulletList) {
				if (checkCollision(enemy, bullet)) {
					EnemiesList.remove(enemy);
					Score++;
					
					// 15% chance to drop health potion
					if (Math.random() < 0.15) {
						PotionsList.add(new GameObject("res/potion.png", 50, 50, new Point3f(enemy.getCentre().getX(), enemy.getCentre().getY(), 0)));
					}
					
					Integer pierce = bulletPierces.get(bullet);
					if (pierce == null) pierce = 0;
					
					if (pierce <= 1) {
						BulletList.remove(bullet);
						bulletVelocities.remove(bullet);
						bulletPierces.remove(bullet);
					} else {
						bulletPierces.put(bullet, pierce - 1);
					}
				}  
			}
			
			// Player 1 vs Enemy
			if (checkCollision(Player, enemy)) {
				handlePlayerHit();
				EnemiesList.remove(enemy);
			}
			
			// Player 2 vs Enemy
			if (checkCollision(Player2, enemy)) {
				handlePlayerHit();
				EnemiesList.remove(enemy);
			}
		}
	}

	private boolean checkCollision(GameObject obj1, GameObject obj2) {
		return Math.abs(obj1.getCentre().getX() - obj2.getCentre().getX()) < (obj1.getWidth() + obj2.getWidth()) / 2
			&& Math.abs(obj1.getCentre().getY() - obj2.getCentre().getY()) < (obj1.getHeight() + obj2.getHeight()) / 2;
	}

	private void handlePlayerHit() {
		Lives--;
		if (Lives <= 0) {
			isGameOver = true;
		} else {
			// Reset player positions roughly
			Player.getCentre().setX(400); Player.getCentre().setY(500);
			Player2.getCentre().setX(600); Player2.getCentre().setY(500);
		}
	}

	private void enemyLogic() {
		for (GameObject enemy : EnemiesList) {
			// Find nearest player
			GameObject target = (getDistance(enemy, Player) < getDistance(enemy, Player2)) ? Player : Player2;
			
			float dx = target.getCentre().getX() - enemy.getCentre().getX();
			float dy = target.getCentre().getY() - enemy.getCentre().getY();
			
			// Separation logic (so they don't clump up into a single point)
			float separationDx = 0;
			float separationDy = 0;
			int count = 0;
			for (GameObject otherEnemy : EnemiesList) {
				if (enemy != otherEnemy) {
					float d = getDistance(enemy, otherEnemy);
					if (d > 0 && d < 75) { // 75 pixels push radius
						separationDx += (enemy.getCentre().getX() - otherEnemy.getCentre().getX());
						separationDy += (enemy.getCentre().getY() - otherEnemy.getCentre().getY());
						count++;
					}
				}
			}
			
			if (count > 0) {
				separationDx /= count;
				separationDy /= count;
				float sepLen = (float) Math.sqrt(separationDx*separationDx + separationDy*separationDy);
				if (sepLen > 0) {
					separationDx /= sepLen;
					separationDy /= sepLen;
				}
			}
			
			float length = (float) Math.sqrt(dx*dx + dy*dy);
			float finalDx = 0; float finalDy = 0;
			if (length > 0) {
				finalDx = (dx/length);
				finalDy = (dy/length);
			} else {
				finalDy = 1; 
			}
			
			// Blend target tracking with separation 
			float blendWeight = 1.0f; // pull towards target
			float sepWeight = 1.5f;   // push away heavily from other enemies to create realistic horde
			
			float nextDx = finalDx * blendWeight + separationDx * sepWeight;
			float nextDy = finalDy * blendWeight + separationDy * sepWeight;
			
			// Normalize final vector and apply difficulty speed
			float speed = (0.5f + (Level * 0.2f)) * difficultySpeedMult;
			float nextLen = (float) Math.sqrt(nextDx*nextDx + nextDy*nextDy);
			if (nextLen > 0) {
				nextDx = (nextDx / nextLen) * speed;
				nextDy = (nextDy / nextLen) * speed;
				enemy.getCentre().ApplyVector(new Vector3f(nextDx, nextDy, 0));
				
				if (nextDx < 0) enemy.setFacingRight(false);
				else if (nextDx > 0) enemy.setFacingRight(true);
			}
			 
			// Bounds check cleanup
			if (enemy.getCentre().getY() > 1400 || enemy.getCentre().getY() < -400 || enemy.getCentre().getX() < -400 || enemy.getCentre().getX() > 1400) {
				EnemiesList.remove(enemy);
				Score--; 
			} 
		}
		
		// Spawn more enemies if room on screen and still have remaining spawns
		int maxEnemies = (int) ((4 + (Level * 2)) * difficultySpawnMult);
		if (EnemiesList.size() < maxEnemies && enemiesToSpawn > 0) {
			spawnEnemy();
			enemiesToSpawn--;
		}
	}

	private float getDistance(GameObject obj1, GameObject obj2) {
		float dx = obj1.getCentre().getX() - obj2.getCentre().getX();
		float dy = obj1.getCentre().getY() - obj2.getCentre().getY();
		return (float) Math.sqrt(dx*dx + dy*dy);
	}

	private void bulletLogic() {
		for (GameObject temp : BulletList) {
			// Spin the slashing sword rapidly
			temp.setRotation(temp.getRotation() + 35);
			
			Vector3f vel = bulletVelocities.get(temp);
			if (vel != null) {
				temp.getCentre().ApplyVector(vel);
			} else {
				float speed = -7.0f;
				temp.getCentre().ApplyVector(new Vector3f(0, speed, 0)); // Move up
			}
			
			if (temp.getCentre().getY() < -50 || temp.getCentre().getY() > 1050 || temp.getCentre().getX() < -50 || temp.getCentre().getX() > 1050) {
				BulletList.remove(temp);
				bulletVelocities.remove(temp);
				bulletPierces.remove(temp);
			} 
		} 
	}

	private void playerLogic() {
		// Player 1 (WASD Movement - Normalized)
		float p1dx = 0; float p1dy = 0;
		if (controller.isKeyAPressed()) p1dx -= 1;
		if (controller.isKeyDPressed()) p1dx += 1;
		if (controller.isKeyWPressed()) p1dy -= 1;
		if (controller.isKeySPressed()) p1dy += 1;
		
		if (p1dx != 0 || p1dy != 0) {
			float len = (float)Math.sqrt(p1dx*p1dx + p1dy*p1dy);
			Player.getCentre().ApplyVector(new Vector3f((p1dx/len) * 5.0f, (p1dy/len) * 5.0f, 0));
			p1Facing = new Vector3f(p1dx/len, p1dy/len, 0);
			if (p1dx < 0) Player.setFacingRight(false);
			else if (p1dx > 0) Player.setFacingRight(true);
		}
		
		// Player 1 Mouse/Space Attack
		if (controller.isKeySpacePressed() || controller.isMousePressed()) {
			CreateSlashAttack(Player);
			controller.setKeySpacePressed(false);
			controller.setMousePressed(false);
		} 

		// Player 2 (Arrow Movement - Normalized)
		float p2dx = 0; float p2dy = 0;
		if (controller.isKeyLeftPressed()) p2dx -= 1;
		if (controller.isKeyRightPressed()) p2dx += 1;
		if (controller.isKeyUPPressed()) p2dy -= 1;
		if (controller.isKeyDownPressed()) p2dy += 1;
		
		if (p2dx != 0 || p2dy != 0) {
			float len = (float)Math.sqrt(p2dx*p2dx + p2dy*p2dy);
			Player2.getCentre().ApplyVector(new Vector3f((p2dx/len) * 5.0f, (p2dy/len) * 5.0f, 0));
			p2Facing = new Vector3f(p2dx/len, p2dy/len, 0);
			if (p2dx < 0) Player2.setFacingRight(false);
			else if (p2dx > 0) Player2.setFacingRight(true);
		}
		
		// Player 2 Enter Attack
		if (controller.isKeyEnterPressed()) {
			CreateSlashAttack(Player2);
			controller.setKeyEnterPressed(false);
		}
		
		// Keep players in bounds
		clampPosition(Player);
		clampPosition(Player2);
	}

	private void clampPosition(GameObject obj) {
		if (obj.getCentre().getX() < 0) obj.getCentre().setX(0);
		if (obj.getCentre().getX() > 950) obj.getCentre().setX(950);
		if (obj.getCentre().getY() < 0) obj.getCentre().setY(0);
		if (obj.getCentre().getY() > 950) obj.getCentre().setY(950);
	}

	private void CreateSlashAttack(GameObject source) {
		int numSwords = Level;
		if (numSwords > 8) numSwords = 8; // Cap at 8 to prevent screen clutter
		
		int size = 64; 
		
		float speed = 7.0f + (Level * 0.5f);
		float dx = 0;
		float dy = -speed;
		
		GameObject target = null;
		float minDist = Float.MAX_VALUE;
		for (GameObject e : EnemiesList) {
			float d = getDistance(source, e);
			if (d < minDist) { minDist = d; target = e; }
		}
		
		if (target != null && minDist > 0) {
			dx = target.getCentre().getX() - source.getCentre().getX();
			dy = target.getCentre().getY() - source.getCentre().getY();
			float length = (float) Math.sqrt(dx*dx + dy*dy);
			dx = (dx/length) * speed;
			dy = (dy/length) * speed;
		}
		
		double baseAngle = Math.atan2(dy, dx);
		double spread = Math.toRadians(15);
		
		for (int i = 0; i < numSwords; i++) {
			GameObject bullet = new GameObject("res/sword.png", size, size, new Point3f(source.getCentre().getX(), source.getCentre().getY(), 0.0f));
			BulletList.add(bullet);
			
			// Pierce count scales slightly with level
			int pierce = 1 + (Level / 3);
			bulletPierces.put(bullet, pierce);
			
			double offsetAngle = 0;
			if (numSwords > 1) {
				offsetAngle = spread * (i - (numSwords - 1) / 2.0f);
			}
			double finalAngle = baseAngle + offsetAngle;
			
			float velX = (float) (Math.cos(finalAngle) * speed);
			float velY = (float) (Math.sin(finalAngle) * speed);
			
			bulletVelocities.put(bullet, new Vector3f(velX, velY, 0));
		}
	}

	public GameObject getPlayer() { return Player; }
	public GameObject getPlayer2() { return Player2; }
	public CopyOnWriteArrayList<GameObject> getEnemies() { return EnemiesList; }
	public CopyOnWriteArrayList<GameObject> getBullets() { return BulletList; }
	public int getScore() { return Score; }
	public int getLives() { return Lives; }
	public int getLevel() { return Level; }
	public boolean isGameOver() { return isGameOver; }
	public GameObject getNextLevelHole() { return nextLevelHole; }
	public CopyOnWriteArrayList<GameObject> getPotions() { return PotionsList; }
	
	public void setDifficulty(String diff) {
		if (diff.equals("Hard")) { difficultySpeedMult = 1.5f; difficultySpawnMult = 1.5f; Lives = 2; }
		else if (diff.equals("Nightmare")) { difficultySpeedMult = 2.0f; difficultySpawnMult = 2.0f; Lives = 1; }
		else { difficultySpeedMult = 1.0f; difficultySpawnMult = 1.0f; Lives = 3; }
		
		Level = 1;
		Score = 0;
		enemiesToSpawn = 10 + (Level * 5);
		isGameOver = false; // Just in case
	}
	
	private void saveGame() {
		try (PrintWriter out = new PrintWriter("savegame.txt")) {
			out.println(Level); out.println(Score); out.println(Lives); out.println(enemiesToSpawn);
			out.println(difficultySpeedMult); out.println(difficultySpawnMult);
		} catch (Exception e) { e.printStackTrace(); }
	}
	
	public void loadGame() {
		try (BufferedReader br = new BufferedReader(new FileReader("savegame.txt"))) {
			Level = Integer.parseInt(br.readLine());
			Score = Integer.parseInt(br.readLine());
			Lives = Integer.parseInt(br.readLine());
			enemiesToSpawn = Integer.parseInt(br.readLine());
			String speedMult = br.readLine();
			if (speedMult != null) difficultySpeedMult = Float.parseFloat(speedMult);
			String spawnMult = br.readLine();
			if (spawnMult != null) difficultySpawnMult = Float.parseFloat(spawnMult);
			
			EnemiesList.clear(); BulletList.clear(); PotionsList.clear(); nextLevelHole = null;
			Player.getCentre().setX(400); Player.getCentre().setY(500);
			Player2.getCentre().setX(600); Player2.getCentre().setY(500);
			int spawnCount = Math.min(5 + Level, enemiesToSpawn);
			for(int i=0; i<spawnCount; i++) { spawnEnemy(); enemiesToSpawn--; }
		} catch (Exception e) { e.printStackTrace(); }
	}

}


